import fs from 'node:fs'
import ts from 'typescript'

function extractParams(routePath) {
  const params = []
  const regex = /:([A-Za-z_$][A-Za-z0-9_$]*)(?:\([^)]*\))?([+*?])?/g
  let m
  while ((m = regex.exec(routePath)) !== null) {
    const suffix = m[2] ?? ''
    params.push({
      name: m[1],
      optional: suffix === '?' || suffix === '*',
      repeatable: suffix === '+' || suffix === '*',
    })
  }
  return params
}

function buildParamTypes(params) {
  if (params.length === 0) {
    return { raw: 'Record<never, never>', norm: 'Record<never, never>' }
  }
  const rawFields = params.map((p) => {
    if (p.repeatable) {
      return p.optional ? `${p.name}?: Array<string | number>` : `${p.name}: Array<string | number>`
    }
    return p.optional ? `${p.name}?: string | number` : `${p.name}: string | number`
  })
  const normFields = params.map((p) => {
    if (p.repeatable) {
      return p.optional ? `${p.name}?: string[]` : `${p.name}: string[]`
    }
    return p.optional ? `${p.name}?: string` : `${p.name}: string`
  })
  return {
    raw: `{ ${rawFields.join('; ')} }`,
    norm: `{ ${normFields.join('; ')} }`,
  }
}

function joinPath(base, seg) {
  if (seg.startsWith('/')) return seg
  if (seg === '') return base || '/'
  if (base === '' || base === '/') return '/' + seg
  return base + '/' + seg
}

function unwrapExpression(expr) {
  while (true) {
    if (ts.isAsExpression(expr)) {
      expr = expr.expression
    } else if (ts.isSatisfiesExpression(expr)) {
      expr = expr.expression
    } else if (ts.isParenthesizedExpression(expr)) {
      expr = expr.expression
    } else {
      break
    }
  }
  return expr
}

function getStringLiteralProp(obj, key) {
  for (const prop of obj.properties) {
    if (ts.isPropertyAssignment(prop) && ts.isIdentifier(prop.name) && prop.name.text === key) {
      const val = unwrapExpression(prop.initializer)
      if (ts.isStringLiteral(val)) return val.text
    }
  }
  return undefined
}

function getArrayProp(obj, key) {
  for (const prop of obj.properties) {
    if (ts.isPropertyAssignment(prop) && ts.isIdentifier(prop.name) && prop.name.text === key) {
      const val = unwrapExpression(prop.initializer)
      if (ts.isArrayLiteralExpression(val)) return val
    }
  }
  return undefined
}

function parseRouteNode(expr) {
  const obj = unwrapExpression(expr)
  if (!ts.isObjectLiteralExpression(obj)) return null

  const routePath = getStringLiteralProp(obj, 'path')
  if (routePath === undefined) return null

  const name = getStringLiteralProp(obj, 'name')
  const childrenArr = getArrayProp(obj, 'children')

  const children = []
  if (childrenArr) {
    for (const el of childrenArr.elements) {
      const child = parseRouteNode(el)
      if (child) children.push(child)
    }
  }

  return { path: routePath, name, children: children.length ? children : undefined }
}

function parseRoutesFromFile(filePath) {
  const src = fs.readFileSync(filePath, 'utf-8')
  const sourceFile = ts.createSourceFile(filePath, src, ts.ScriptTarget.ESNext, true)

  for (const stmt of sourceFile.statements) {
    if (!ts.isVariableStatement(stmt)) continue
    const hasExport = stmt.modifiers?.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)
    if (!hasExport) continue

    for (const decl of stmt.declarationList.declarations) {
      if (!ts.isIdentifier(decl.name) || decl.name.text !== 'routes') continue
      if (!decl.initializer) continue

      const init = unwrapExpression(decl.initializer)
      if (!ts.isArrayLiteralExpression(init)) continue

      const routes = []
      for (const el of init.elements) {
        const node = parseRouteNode(el)
        if (node) routes.push(node)
      }
      return routes
    }
  }
  return []
}

function collectDescendantNames(nodes) {
  const names = []
  for (const node of nodes) {
    if (node.name) names.push(node.name)
    if (node.children) names.push(...collectDescendantNames(node.children))
  }
  return names
}

function flattenRoutes(nodes, basePathArg) {
  const entries = []

  for (const node of nodes) {
    const fullPath = joinPath(basePathArg, node.path)
    const params = extractParams(fullPath)
    const { raw, norm } = buildParamTypes(params)

    if (node.name) {
      const childNames = node.children ? collectDescendantNames(node.children) : []
      entries.push({
        name: node.name,
        fullPath,
        rawParams: raw,
        normParams: norm,
        childNames,
      })
    }

    if (node.children) {
      entries.push(...flattenRoutes(node.children, fullPath))
    }
  }

  return entries
}

function generateDts(entries) {
  const lines = [
    `/* eslint-disable */`,
    `/* prettier-ignore */`,
    `// @ts-nocheck`,
    `// noinspection JSUnusedGlobalSymbols`,
    `// Generated by route-types-generator`,
    `// biome-ignore lint: disable`,
    ``,
    `import type { RouteRecordInfo } from "vue-router";`,
    ``,
    `export interface RouteNamedMap {`,
  ]

  for (const e of entries) {
    const childNamesType =
      e.childNames.length > 0 ? e.childNames.map((n) => JSON.stringify(n)).join(' | ') : 'never'

    lines.push(`  ${JSON.stringify(e.name)}: RouteRecordInfo<`)
    lines.push(`    ${JSON.stringify(e.name)},`)
    lines.push(`    ${JSON.stringify(e.fullPath)},`)
    lines.push(`    ${e.rawParams},`)
    lines.push(`    ${e.normParams},`)
    lines.push(`    ${childNamesType}`)
    lines.push(`  >;`)
  }

  lines.push(`}`)
  lines.push(``)
  lines.push(`declare module "vue-router" {`)
  lines.push(`  interface TypesConfig {`)
  lines.push(`    RouteNamedMap: RouteNamedMap;`)
  lines.push(`  }`)
  lines.push(`}`)
  lines.push(``)
  lines.push(`export type RouteName = keyof RouteNamedMap;`)
  lines.push(``)

  return lines.join('\n')
}

export function generateRouteTypes(routesFile, outFile) {
  if (!fs.existsSync(routesFile)) {
    console.warn(`[route-types-generator] 找不到路由文件: ${routesFile}`)
    return false
  }

  const nodes = parseRoutesFromFile(routesFile)
  const entries = flattenRoutes(nodes, '')
  const dts = generateDts(entries)

  const existing = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf-8') : ''
  if (existing !== dts) {
    fs.writeFileSync(outFile, dts, 'utf-8')
    console.log(`[route-types-generator] 已更新 route-types.gen.d.ts (${entries.length} 个路由)`)
    return true
  }
  return false
}
