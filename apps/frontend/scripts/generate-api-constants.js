/**
 * This script parses types.gen.ts and generates API constants for requests.
 * Run: node scripts/generate-api-constants.js
 */

import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { loadOpenApiSpec } from './lib/openapi-resolver.js'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const TYPES_FILE_PATH = path.resolve(__dirname, '../src/client/types.gen.ts')
const OUTPUT_FILE_PATH = path.resolve(__dirname, '../src/client/api-endpoints.gen.ts')
async function fetchOpenApiSpec() {
  return loadOpenApiSpec()
}

/**
 * Extract operationId -> method mapping from OpenAPI spec.
 * @param {any} spec
 * @returns {Record<string, string>}
 */
function extractMethodMapping(spec) {
  /** @type {Record<string, string>} */
  const mapping = {}
  for (const methods of Object.values(spec.paths || {})) {
    for (const [method, operation] of Object.entries(methods)) {
      if (!operation || typeof operation !== 'object' || !operation.operationId) continue

      const operationId = String(operation.operationId)
      const camelCaseId = operationId.replace(
        /([A-Z]+)([A-Z][a-z])/g,
        (_match, capitals, lastPart) => {
          return capitals.charAt(0) + capitals.slice(1).toLowerCase() + lastPart
        },
      )

      mapping[camelCaseId] = method.toUpperCase()
    }
  }

  return mapping
}

/**
 * @typedef {Object} ApiEndpoint
 * @property {string} name
 * @property {string} originalTypeName
 * @property {string} url
 * @property {'GET' | 'POST' | 'PUT' | 'DELETE' | 'PATCH'} method
 * @property {boolean} hasBody
 * @property {boolean} hasPath
 * @property {boolean} hasQuery
 * @property {string | undefined} bodyType
 * @property {string[]} pathParams
 * @property {string[]} queryParams
 */

/**
 * Extract API endpoint data types from types.gen.ts content
 * @param {string} content
 * @param {Record<string, string>} methodMapping
 * @returns {ApiEndpoint[]}
 */
function extractDataTypes(content, methodMapping) {
  /** @type {ApiEndpoint[]} */
  const endpoints = []

  // Match patterns like: export type AuthRefreshTokenData = { ... } or GetAllUsersData2 = { ... }
  // Support both 'Data' and 'Data2' suffixes
  const typePattern = /export type (\w+Data\d*) = \{([\s\S]*?)^\}/gm

  let match
  while ((match = typePattern.exec(content)) !== null) {
    const typeName = match[1]
    const typeBody = match[2]

    // Extract url - this is required
    const urlMatch = typeBody.match(/url:\s*['"]([^'"]+)['"]/)
    if (!urlMatch) continue

    const url = urlMatch[1]

    // Check body: if body is followed by a type name (not 'never'), it has body
    // Match: body?: Type or body: Type (but not body?: never)
    const bodyMatch = typeBody.match(/body\??:\s*(\w+|never)/)
    const hasBody = bodyMatch && bodyMatch[1] !== 'never'
    const bodyType = hasBody ? bodyMatch[1] : undefined

    // Check path: if path contains properties, it has path params
    const pathMatch = typeBody.match(/path\??:\s*(\{[\s\S]*?\n\s*\}|never)/)
    const hasPath = pathMatch && !pathMatch[1].includes('never')

    // Extract path params
    /** @type {string[]} */
    let pathParams = []
    if (hasPath && pathMatch) {
      const pathParamsMatch = pathMatch[1].matchAll(/(\w+)\??:/g)
      pathParams = [...pathParamsMatch].map((m) => m[1])
    }

    // Check query: if query contains properties, it has query params
    const queryMatch = typeBody.match(/query\??:\s*(\{[\s\S]*?\n\s*\}|never)/)
    const hasQuery = queryMatch && !queryMatch[1].includes('never')

    // Extract query params
    /** @type {string[]} */
    let queryParams = []
    if (hasQuery && queryMatch) {
      const queryParamsMatch = queryMatch[1].matchAll(/(\w+)\??:/g)
      queryParams = [...queryParamsMatch].map((m) => m[1])
    }

    const endpointName = typeName.replace(/Data\d*$/, '')
    const method = methodMapping[endpointName] || (hasBody ? 'POST' : 'GET')

    endpoints.push({
      name: endpointName,
      originalTypeName: typeName,
      url,
      method,
      hasBody,
      hasPath,
      hasQuery,
      bodyType,
      pathParams,
      queryParams,
    })
  }

  return endpoints
}

/**
 * Convert PascalCase/camelCase to SCREAMING_SNAKE_CASE
 * @param {string} name
 * @returns {string}
 */
function toConstantName(name) {
  return name
    .replace(/([a-z])([A-Z])/g, '$1_$2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2')
    .toUpperCase()
}

/**
 * Generate the constants file content
 * @param {ApiEndpoint[]} endpoints
 * @returns {string}
 */
function generateConstants(endpoints) {
  const lines = [
    '// This file is auto-generated by scripts/generate-api-constants.js',
    '// Do not edit manually. Run `npm run generate-client` to regenerate.',
    '',
    "import type * as Types from './types.gen'",
    '',
    '// ============== HTTP Methods ==============',
    'export const HTTP_METHOD = {',
    "  GET: 'GET',",
    "  POST: 'POST',",
    "  PUT: 'PUT',",
    "  DELETE: 'DELETE',",
    "  PATCH: 'PATCH',",
    '} as const',
    '',
    'export type HttpMethod = (typeof HTTP_METHOD)[keyof typeof HTTP_METHOD]',
    '',
    '// ============== API Endpoint Interface ==============',
    'export interface ApiEndpointConfig {',
    '  url: string',
    '  method: HttpMethod',
    '  hasBody: boolean',
    '  hasPath: boolean',
    '  hasQuery: boolean',
    '}',
    '',
    '// ============== API Endpoints ==============',
  ]

  for (const endpoint of endpoints) {
    const constName = toConstantName(endpoint.name)
    lines.push(`export const ${constName} = {`)
    lines.push(`  url: '${endpoint.url}',`)
    lines.push(`  method: HTTP_METHOD.${endpoint.method},`)
    lines.push(`  hasBody: ${!!endpoint.hasBody},`)
    lines.push(`  hasPath: ${!!endpoint.hasPath},`)
    lines.push(`  hasQuery: ${!!endpoint.hasQuery},`)
    lines.push('} as const satisfies ApiEndpointConfig')
    lines.push('')
  }

  // Generate a map of all endpoints
  lines.push('// ============== All API Endpoints Map ==============')
  lines.push('export const API_ENDPOINTS = {')
  for (const endpoint of endpoints) {
    const constName = toConstantName(endpoint.name)
    lines.push(`  ${endpoint.name}: ${constName},`)
  }
  lines.push('} as const')
  lines.push('')

  // Generate URL builder functions for endpoints with path/query params
  lines.push('// ============== URL Builder Functions ==============')
  for (const endpoint of endpoints) {
    const hasPathParams = endpoint.hasPath && endpoint.pathParams.length > 0
    const hasQueryParams = endpoint.hasQuery && endpoint.queryParams.length > 0
    if (!hasPathParams && !hasQueryParams) continue

    const funcName = `build${endpoint.name}Url`
    const params = []
    if (hasPathParams) {
      params.push(...endpoint.pathParams.map((p) => `${p}: string | number`))
    }
    if (hasQueryParams)
      params.push(`query?: Partial<NonNullable<Types.${endpoint.originalTypeName}['query']>>`)

    lines.push(`export function ${funcName}(${params.join(', ')}): string {`)
    lines.push(`  let url: string = '${endpoint.url}'`)

    if (hasPathParams) {
      for (const param of endpoint.pathParams)
        lines.push(`  url = url.replace('{${param}}', encodeURIComponent(String(${param})))`)
    }

    if (hasQueryParams) {
      lines.push('  const queryParams = new URLSearchParams()')
      endpoint.queryParams.forEach((param, index) => {
        const valueName = `queryValue${index}`
        lines.push(`  const ${valueName} = query?.['${param}']`)
        lines.push(`  if (Array.isArray(${valueName})) {`)
        lines.push(`    ${valueName}.forEach((item) => {`)
        lines.push(
          `      if (item !== undefined && item !== null) queryParams.append('${param}', String(item))`,
        )
        lines.push('    })')
        lines.push(`  } else if (${valueName} !== undefined && ${valueName} !== null) {`)
        lines.push(`    queryParams.set('${param}', String(${valueName}))`)
        lines.push('  }')
      })
      lines.push('  const queryString = queryParams.toString()')
      lines.push("  if (queryString) url += '?' + queryString")
    }

    lines.push('  return url')
    lines.push('}')
    lines.push('')
  }

  // Generate type-safe request configuration types
  lines.push('// ============== Type-safe Request Configuration Types ==============')
  for (const endpoint of endpoints) {
    const typeName = `${endpoint.name}RequestConfig`
    const dataTypeName = `Types.${endpoint.originalTypeName}`

    lines.push(`export type ${typeName} = {`)
    lines.push(`  endpoint: typeof ${toConstantName(endpoint.name)}`)

    if (endpoint.hasBody) {
      lines.push(`  body: ${dataTypeName}['body']`)
    }
    if (endpoint.hasPath) {
      lines.push(`  path: NonNullable<${dataTypeName}['path']>`)
    }
    if (endpoint.hasQuery) {
      lines.push(`  query: NonNullable<${dataTypeName}['query']>`)
    }

    lines.push('}')
    lines.push('')
  }

  return lines.join('\n')
}

async function main() {
  console.log('📖 Reading types.gen.ts...')

  if (!fs.existsSync(TYPES_FILE_PATH)) {
    console.error(`❌ Error: ${TYPES_FILE_PATH} not found`)
    process.exit(1)
  }

  const content = fs.readFileSync(TYPES_FILE_PATH, 'utf-8')
  console.log('🌐 Fetching OpenAPI spec...')
  const spec = await fetchOpenApiSpec()
  const methodMapping = extractMethodMapping(spec)

  console.log('🔍 Extracting API endpoint types...')
  const endpoints = extractDataTypes(content, methodMapping)

  console.log(`✅ Found ${endpoints.length} API endpoints:`)
  endpoints.forEach((ep) => {
    console.log(`   - ${ep.name}: ${ep.method} ${ep.url}`)
  })

  console.log('📝 Generating constants file...')
  const output = generateConstants(endpoints)

  fs.writeFileSync(OUTPUT_FILE_PATH, output, 'utf-8')

  console.log(`✨ Generated: ${OUTPUT_FILE_PATH}`)
}

main().catch(console.error)
