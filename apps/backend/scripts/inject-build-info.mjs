import { execSync } from "child_process";
import { readFileSync, mkdirSync, writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, "..");

function git(cmd) {
  try {
    return execSync(cmd, { cwd: root, encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

const commitHash = git("git rev-parse HEAD");
const commitHashShort = git("git rev-parse --short HEAD");
const branch = git("git rev-parse --abbrev-ref HEAD");
const commitMessage = git("git log -1 --pretty=%s");
const commitTime = git("git log -1 --pretty=%cI");
const { version } = JSON.parse(readFileSync(resolve(root, "package.json"), "utf8"));
const buildTime = new Date().toISOString();

const content = `// Auto-generated by scripts/inject-build-info.mjs — DO NOT EDIT
export const BUILD_INFO = {
  version: ${JSON.stringify(version)},
  commitHash: ${JSON.stringify(commitHash)},
  commitHashShort: ${JSON.stringify(commitHashShort)},
  branch: ${JSON.stringify(branch)},
  commitMessage: ${JSON.stringify(commitMessage)},
  commitTime: ${JSON.stringify(commitTime)},
  buildTime: ${JSON.stringify(buildTime)},
} as const;
`;

const outDir = resolve(root, "src/generated");
mkdirSync(outDir, { recursive: true });
writeFileSync(resolve(outDir, "buildInfo.ts"), content, "utf8");
console.log(`✓ Build info injected (${commitHashShort} @ ${branch})`);
